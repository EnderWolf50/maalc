"""The field structure of every data file, committed as tests/data_structure.json (格式版本, #769, ADR 0012).

  uv run python tools/data_structure.py      # regenerate the snapshot after FORMAT in agent/resource_package.py went up

An older program applies a package's data only when its FORMAT equals the one it knows, so a change to what a data file's
fields are has to raise FORMAT. tests/test_game_data.py fails when the files under assets/resource/base/data/ (JSON and
YAML; images are not structure) no longer have the structure the snapshot records at the current FORMAT.

A file's structure is the set of `path: type` lines of everything in it. Values, ids, names used as keys and the number of
rows are left out; a field's name, its type and its nesting are in. A field renamed therefore shows as one line gone and one
new. A field whose meaning changes under the same name shows nothing, so a change of meaning gets a new field name (ADR 0012).

- A dict whose keys are all snake_case words is an `object`: its keys are fields and each is listed.
- A dict with any other key (an id, a number, a name such as `Yi Sang`) is a `map`: its keys are data and stand as `*`.
- A list's rows are one `[]` path; a field present in some rows only is listed once. `null` is listed only for a field
  that is never anything else.
- `int` and `float` are both `number`.

The snapshot is rewritten only when its structure is unchanged or FORMAT went up, so a regenerated file cannot hide a change
that was not announced by the bump.
"""

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "agent"))
import resource_package as rp  # noqa: E402

DATA = REPO / "assets" / "resource" / "base" / "data"
SNAPSHOT = REPO / "tests" / "data_structure.json"
NOTE = "Generated by tools/data_structure.py: the field structure of each data file at FORMAT in agent/resource_package.py."
FIELD = re.compile(r"^[a-z][a-z0-9_]*$")
REGEN = "uv run python tools/data_structure.py"


def _type(value) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, (int, float)):
        return "number"
    return type(value).__name__


def _walk(value, path: str, out: dict[str, set[str]]) -> None:
    if isinstance(value, dict):
        is_map = any(not (isinstance(k, str) and FIELD.match(k)) for k in value)
        out.setdefault(path, set()).add("map" if is_map else "object")
        for key, item in value.items():
            _walk(item, f"{path}.*" if is_map else f"{path}.{key}", out)
    elif isinstance(value, list):
        out.setdefault(path, set()).add("list")
        for item in value:
            _walk(item, f"{path}[]", out)
    else:
        out.setdefault(path, set()).add(_type(value))


def structure(value) -> list[str]:
    """The sorted `path: type` lines of one parsed data file."""
    found: dict[str, set[str]] = {}
    _walk(value, "$", found)
    lines = []
    for path in sorted(found):
        types = found[path] - {"null"} or found[path]
        lines.append(f"{path}: {'|'.join(sorted(types))}")
    return lines


def load_data_file(path: Path):
    text = path.read_text(encoding="utf-8")
    return json.loads(text) if path.suffix == ".json" else yaml.safe_load(text)


def snapshot_files(data: Path) -> dict[str, list[str]]:
    """The structure of every JSON and YAML file under `data`, by POSIX path relative to it."""
    files = sorted(p for p in Path(data).rglob("*") if p.is_file() and p.suffix in (".json", ".yaml"))
    return {p.relative_to(data).as_posix(): structure(load_data_file(p)) for p in files}


def load_snapshot(path: Path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _differences(old: dict[str, list[str]], new: dict[str, list[str]]) -> list[str]:
    out = []
    for name in sorted(old.keys() | new.keys()):
        if name not in new:
            out.append(f"{name}: removed")
        elif name not in old:
            out.append(f"{name}: new file")
        else:
            out += [f"{name}: - {line}" for line in old[name] if line not in new[name]]
            out += [f"{name}: + {line}" for line in new[name] if line not in old[name]]
    return out


def check(snapshot: dict, files: dict[str, list[str]], format_version: int) -> str | None:
    """None when the snapshot records exactly `files` at `format_version`, else what to do about it."""
    changes = _differences(snapshot["files"], files)
    detail = "\n".join(f"  {line}" for line in changes)
    if changes and snapshot["format"] == format_version:
        return (f"the field structure of the data files changed but FORMAT is still {format_version}: an older program would "
                f"read the new files wrongly. Raise FORMAT in agent/resource_package.py, then regenerate the snapshot with "
                f"`{REGEN}`.\n{detail}")
    if changes or snapshot["format"] != format_version:
        return (f"tests/data_structure.json records FORMAT {snapshot['format']}, the program has {format_version}: regenerate "
                f"the snapshot with `{REGEN}`.\n{detail}")
    return None


def regenerate(data: Path, out: Path, format_version: int) -> str | None:
    """Write the snapshot; a message and no write when the structure changed and FORMAT did not go up."""
    files = snapshot_files(data)
    if Path(out).exists():
        old = load_snapshot(out)
        if old["format"] == format_version and old["files"] != files:
            return ("the structure changed but FORMAT in agent/resource_package.py did not go up: raise FORMAT first, then run "
                    f"`{REGEN}` again.\n" + "\n".join(f"  {line}" for line in _differences(old["files"], files)))
    Path(out).write_text(json.dumps({"note": NOTE, "format": format_version, "files": files}, indent=1, ensure_ascii=False) + "\n",
                         encoding="utf-8")
    return None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", type=Path, default=DATA)
    ap.add_argument("--out", type=Path, default=SNAPSHOT)
    args = ap.parse_args(argv)
    problem = regenerate(args.data, args.out, rp.FORMAT)
    if problem:
        print(problem, file=sys.stderr)
        return 1
    print(f"wrote {args.out} (FORMAT {rp.FORMAT})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
